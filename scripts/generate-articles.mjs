import fs from 'fs';
import path from 'path';
import matter from 'gray-matter';
import { marked } from 'marked';

const CONTENT_DIR = path.join(process.cwd(), 'content');
const OUT_FILE = path.join(process.cwd(), 'src/lib/articles-generated.ts');
const LOCALES = ['en', 'ja', 'zh', 'zh-TW', 'es', 'fr', 'de', 'ko', 'it', 'pt', 'ru'];

function countWords(text) {
  const cjk = (text.match(/[一-鿿぀-ゟ゠-ヿ]/g) || []).length;
  const latin = text.replace(/[一-鿿぀-ゟ゠-ヿ]/g, ' ').split(/\s+/).filter(Boolean).length;
  return cjk + latin;
}

function readMdFile(filePath) {
  try {
    const raw = fs.readFileSync(filePath, 'utf-8');
    return matter(raw);
  } catch {
    return null;
  }
}

function getSlugsFromDir(dir) {
  try {
    return fs.readdirSync(dir).filter(f => f.endsWith('.md')).map(f => f.replace(/\.md$/, ''));
  } catch {
    return [];
  }
}

function buildEntry(file) {
  return {
    title: file.data.title,
    date: file.data.date,
    modified: file.data.modified || null,
    summary: file.data.summary,
    image: file.data.image || null,
    tags: file.data.tags || [],
    section: file.data.section === 'guides' ? 'guides' : 'news',
    content: marked.parse(file.content),
    wordCount: countWords(file.content),
  };
}

// Collect all articles (root English + locale versions)
const rootSlugs = getSlugsFromDir(CONTENT_DIR);
const articles = {};

for (const slug of rootSlugs) {
  // Root (English) version
  const enFile = readMdFile(path.join(CONTENT_DIR, `${slug}.md`));
  if (enFile) {
    articles[slug] = articles[slug] || {};
    articles[slug]['en'] = buildEntry(enFile);
  }

  // Locale versions
  for (const locale of LOCALES) {
    if (locale === 'en') continue;
    const localeDir = path.join(CONTENT_DIR, locale);
    const localeFile = readMdFile(path.join(localeDir, `${slug}.md`));
    if (localeFile) {
      articles[slug] = articles[slug] || {};
      articles[slug][locale] = buildEntry(localeFile);
    }
  }
}

// Also pick up locale-specific articles not in root
for (const locale of LOCALES) {
  if (locale === 'en') continue;
  const localeDir = path.join(CONTENT_DIR, locale);
  const localeSlugs = getSlugsFromDir(localeDir);
  for (const slug of localeSlugs) {
    if (articles[slug]?.[locale]) continue; // already processed
    const localeFile = readMdFile(path.join(localeDir, `${slug}.md`));
    if (localeFile) {
      articles[slug] = articles[slug] || {};
      articles[slug][locale] = buildEntry(localeFile);
    }
  }
}

const output = `// Auto-generated by scripts/generate-articles.mjs — DO NOT EDIT
export type ArticleSection = 'news' | 'guides';

export interface ArticleData {
  title: string;
  date: string;
  modified: string | null;
  summary: string;
  image: string | null;
  tags: string[];
  section: ArticleSection;
  content: string;
  wordCount: number;
}

export const ARTICLES: Record<string, Record<string, ArticleData>> = ${JSON.stringify(articles, null, 2)};
`;

fs.writeFileSync(OUT_FILE, output);
const newsCount = Object.values(articles).filter(a => a.en?.section === 'news').length;
const guidesCount = Object.values(articles).filter(a => a.en?.section === 'guides').length;
const localeOnly = Object.keys(articles).length - newsCount - guidesCount;
console.log(`Generated ${OUT_FILE}: ${newsCount} news, ${guidesCount} guides, ${localeOnly} locale-only (${Object.keys(articles).length} total slugs)`);
